package com.chemlab.ui

/**
 * 实验台上的两种交互模式。
 *
 * 「摆放器材」不再单独占一个模式：在任何模式下长按器材本体即可拖动，
 * 腾出的模式位用来降低小屏上的操作层级。
 */
enum class InteractionMode(val label: String, val hint: String) {
    /** 点击端口两两配对建立连接；点连线中点可断开 */
    CONNECT("连接", "点击端口配对连线；绿色端口是可连接目标；点连线中点可断开"),

    /** 长按拖动摆放器材；点击器材弹出操作栏 */
    OPERATE("操作", "点击器材弹出操作栏；长按器材可拖动位置；拖背景平移画布")
}